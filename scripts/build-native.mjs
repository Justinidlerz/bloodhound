import { NapiCli } from '@napi-rs/cli';
import { copyFileSync, mkdirSync, readFileSync } from 'node:fs';
const targets = JSON.parse(readFileSync('.github/native-targets.json', 'utf8'));
const target = process.argv.includes('--wasi')
  ? targets.find(({ wasi }) => wasi)?.target
  : process.env.CARGO_BUILD_TARGET;
const wasi = targets.find((entry) => entry.target === target)?.wasi;
const outputDir = wasi ? 'artifacts/wasi' : 'dist';
const build = await new NapiCli().build({
  manifestPath: 'native/Cargo.toml',
  packageJsonPath: 'package.json',
  outputDir,
  target,
  platform: true,
  esm: true,
  release: true,
  jsBinding: 'native.js',
  dts: wasi ? 'native.d.cts' : 'native.d.ts',
  dtsHeader:
    "/* Generated by napi-rs. Do not edit. */\nimport type { ScanEntry, ScanOptions, Source, Budgets } from './types.js'" +
    (wasi ? " with { 'resolution-mode': 'import' };" : ';'),
  cargoOptions: ['--locked'],
});
await build.task;
if (wasi) {
  mkdirSync('dist', { recursive: true });
  copyFileSync(`${outputDir}/native.js`, 'dist/native.js');
  copyFileSync(`${outputDir}/native.d.cts`, 'dist/native.d.ts');
}
